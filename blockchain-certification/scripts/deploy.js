// Deploys CertificateRegistry and writes the address into frontend/js/config.js,
// so nobody has to copy-paste addresses by hand.
const fs = require("fs");
const path = require("path");
const { ethers, network } = require("hardhat");

const INSTITUTION = process.env.INSTITUTION_NAME || "My University";

// Read-only RPC used by the verify page (no wallet needed).
// Public endpoints, safe to put in the browser. Never put your Alchemy key here.
const READ_RPC = {
  localhost: "http://127.0.0.1:8545",
  sepolia: "https://ethereum-sepolia-rpc.publicnode.com",
};
const EXPLORER = { localhost: "", sepolia: "https://sepolia.etherscan.io" };

async function main() {
  const [deployer] = await ethers.getSigners();
  console.log(`Network: ${network.name}  Deployer: ${deployer.address}`);

  const registry = await ethers.deployContract("CertificateRegistry", [INSTITUTION]);
  await registry.waitForDeployment();
  const address = await registry.getAddress();
  const receipt = await registry.deploymentTransaction().wait();
  const chainId = Number((await ethers.provider.getNetwork()).chainId);
  console.log(`CertificateRegistry deployed to: ${address} (block ${receipt.blockNumber})`);

  // 1. Keep a record of every network we deployed to
  const recordFile = path.join(__dirname, "..", "deployments.json");
  const record = fs.existsSync(recordFile)
    ? JSON.parse(fs.readFileSync(recordFile, "utf8"))
    : {};
  record[network.name] = {
    chainId,
    address,
    deployBlock: receipt.blockNumber,
    institution: INSTITUTION,
    readRpc: READ_RPC[network.name] || "",
    explorer: EXPLORER[network.name] || "",
    deployedAt: new Date().toISOString(),
  };
  fs.writeFileSync(recordFile, JSON.stringify(record, null, 2) + "\n");

  // 2. Generate the front-end config from that record
  const configFile = path.join(__dirname, "..", "frontend", "js", "config.js");
  const js =
    "// Generated by scripts/deploy.js - do not edit by hand\n" +
    `window.APP_CONFIG = ${JSON.stringify({ networks: record }, null, 2)};\n`;
  fs.writeFileSync(configFile, js);
  console.log("Updated deployments.json and frontend/js/config.js");

  if (network.name === "sepolia") {
    console.log(`Etherscan: https://sepolia.etherscan.io/address/${address}`);
    console.log(
      `Verify source: npx hardhat verify --network sepolia ${address} "${INSTITUTION}"`,
    );
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
